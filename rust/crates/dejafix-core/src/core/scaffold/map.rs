use std::fmt::Write;

use super::types::ManifestInfo;
use crate::core::global::Stack;

fn first_sorted(items: &[String], count: usize) -> String {
    let mut sorted: Vec<&str> = items.iter().map(String::as_str).collect();
    sorted.sort_unstable();
    sorted
        .into_iter()
        .take(count)
        .collect::<Vec<_>>()
        .join(", ")
}

#[must_use]
pub fn project_map_from_stack(
    project_name: &str,
    stack: &Stack,
    info: &ManifestInfo,
) -> Option<String> {
    let description = info.description.as_deref().filter(|text| !text.is_empty());
    let has_signal = !stack.tags.is_empty()
        || !stack.libraries.is_empty()
        || description.is_some()
        || !info.entry_points.is_empty()
        || !info.main_folders.is_empty();
    if !has_signal {
        return None;
    }
    let mut map = format!(
        "# Project Map - {project_name}\n\nStatus: auto-detected from project manifests (an AI session may refine this).\n\n"
    );
    if let Some(description) = description {
        let _ = write!(map, "## Project purpose\n{description}\n\n");
    }
    if !stack.tags.is_empty() || !stack.libraries.is_empty() || !stack.manifest_files.is_empty() {
        map.push_str("## Stack\n");
        if !stack.tags.is_empty() {
            let _ = writeln!(map, "- Tags: {}", first_sorted(&stack.tags, 10));
        }
        if !stack.frameworks.is_empty() {
            let _ = writeln!(
                map,
                "- Frameworks: {}",
                first_sorted(&stack.frameworks, usize::MAX)
            );
        }
        if !stack.libraries.is_empty() {
            let _ = writeln!(
                map,
                "- Key libraries: {}",
                first_sorted(&stack.libraries, 10)
            );
        }
        if !stack.manifest_files.is_empty() {
            let _ = writeln!(map, "- Detected from: {}", stack.manifest_files.join(", "));
        }
        map.push('\n');
    }
    if !info.main_folders.is_empty() {
        map.push_str("## Structure\n");
        for (name, description) in &info.main_folders {
            if description.is_empty() {
                let _ = writeln!(map, "- `{name}/`");
            } else {
                let _ = writeln!(map, "- `{name}/` — {description}");
            }
        }
        map.push('\n');
    }
    if !info.entry_points.is_empty() {
        map.push_str("## Entry points\n");
        for entry in &info.entry_points {
            let _ = writeln!(map, "- {entry}");
        }
        map.push('\n');
    }
    map.push_str(
        "_Generated by `djf init`. Refine via your AI session: add architecture, relationships, suggested first reads, and anything stack detection_\n_missed._\n",
    );
    Some(map)
}

#[must_use]
pub fn stack_summary_suffix(stack: &Stack) -> String {
    let detected = if stack.frameworks.is_empty() {
        first_sorted(&stack.tags, 3)
    } else {
        first_sorted(&stack.frameworks, 3)
    };
    if detected.is_empty() {
        String::new()
    } else {
        format!(" ({detected})")
    }
}
